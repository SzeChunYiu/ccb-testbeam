"""S29c PID timing-energy joint pulse representation benchmark.

This ticket-specific runner reuses the S26c benchmark implementation for the
shared method panel, while changing the ticket metadata, output directory, seed,
and report framing for the newly claimed S29c study.
"""

from __future__ import annotations

import json
import platform
import sys
import time
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

import s25b_1783770201_8222_568f4add_pileup_saturation_recovery as base  # noqa: E402
import s26c_1783800116_3081_430d48e6_pulse_pid_energy_timing_joint_inference_bakeoff as s26c  # noqa: E402


TICKET = "1783826036.4927.55a407fe"
SLUG = "s29c_pid_timing_energy_joint_pulse_representation_benchmark"
OUT = ROOT / "reports" / f"{TICKET}__{SLUG}"
WORKER = "testbeam-laptop-3"
RAW_ROOT_DIR = Path("/home/billy/ccb-data/extracted/root/root")
_S26C_LOAD_CONFIG = s26c.load_config


def sha256(path: Path) -> str:
    return base.sha256_file(path)


def load_config() -> dict:
    cfg = _S26C_LOAD_CONFIG()
    cfg.update(
        {
            "study_id": "S29c",
            "ticket_id": TICKET,
            "title": "PID timing-energy joint pulse representation benchmark",
            "worker": WORKER,
            "output_dir": str(OUT),
            "raw_root_dir": str(RAW_ROOT_DIR),
            "random_seed": 2026071293,
            "max_clean_pulses_per_run_stave": 92,
            "injected_per_train_run": 54,
            "clean_per_train_run": 54,
            "injected_per_heldout_run": 74,
            "clean_per_heldout_run": 74,
        }
    )
    cfg["ml"].update({"bootstrap_samples": 420, "cnn_epochs": 86, "cnn_channels": 14, "max_iter": 260})
    return cfg


def _fmt(value: float) -> str:
    return f"{value:.4g}"


def write_report(
    cfg: dict,
    match: pd.DataFrame,
    templates: pd.DataFrame,
    ranked: pd.DataFrame,
    by_run: pd.DataFrame,
    strata: pd.DataFrame,
    winner: str,
    runtime: float,
) -> None:
    best = ranked.iloc[0]
    trad = ranked[ranked["method"] == "deltaE_over_E_likelihood_template"].iloc[0]
    text = f"""# S29c: PID timing-energy joint pulse representation benchmark

## Abstract

Ticket `{TICKET}` asks for an academic benchmark of joint PID, energy, and timing
inference from B-stack pulse shapes.  The worker was `{WORKER}`.  The analysis
first reproduces the raw ROOT selected-pulse number and then compares a strong
traditional DeltaE/E plus timewalk/template method with ridge, gradient-boosted
trees, MLP, 1D-CNN, and new neural/physics-residual architectures under a
leave-run-out design.

The raw selected-pulse anchor is reproduced directly from ROOT:
`{int(match.iloc[0]['reproduced'])}` selected B-stave pulses versus reference
`{int(match.iloc[0]['report_value'])}`, delta `{int(match.iloc[0]['delta'])}`.

The winner named in `result.json` is **`{winner}`** by the declared held-out
composite score

`C_m = sigma_E,m + 0.01 sigma_t,m + 0.25 (1 - BAcc_PID,m) + 0.05 r_miss,m + 0.05 r_false,m`.

It obtains energy fractional sigma68 `{_fmt(best['energy_fractional_sigma68'])}`
with 95% run-block bootstrap CI
[{_fmt(best['energy_fractional_sigma68_ci_low'])}, {_fmt(best['energy_fractional_sigma68_ci_high'])}],
timing sigma68 `{_fmt(best['time_sigma68_ns'])}` ns with CI
[{_fmt(best['time_sigma68_ns_ci_low'])}, {_fmt(best['time_sigma68_ns_ci_high'])}],
PID balanced accuracy `{_fmt(best['pid_balanced_accuracy'])}`, PID efficiency
`{_fmt(best['pid_efficiency'])}`, and PID purity `{_fmt(best['pid_purity'])}`.

## Raw ROOT reproduction

Raw files were read from `{cfg['raw_root_dir']}`.  Each `h101/HRDv` branch is
reshaped to `(event, channel, sample)` with 18 samples per channel.  The B-stack
selection uses B2/B4/B6/B8, pedestal

`b_c = median_t x_c(t),  t in {{0,1,2,3}}`,

corrected waveform

`y_c(t)=x_c(t)-b_c`,

and selected-pulse condition

`max_t y_c(t)>1000 ADC`.

{s26c.md_table(match, ['quantity', 'report_value', 'reproduced', 'delta', 'pass'])}

## Split, labels, and leakage controls

The split is by source run, with train runs `{cfg['benchmark_runs']['train']}`
and held-out runs `{cfg['benchmark_runs']['heldout']}`.  No source run appears in
both sets.  Templates, likelihood moments, scalers, tree/linear/MLP parameters,
CNN weights, and transformer weights are fit using train-run events only.  Run
identifier and event identifier are kept for grouping and audit, not as model
features.

The endpoint is a controlled raw-waveform benchmark rather than an external PID
measurement.  Clean B-stack residuals are read from ROOT; doublet truths are
generated by controlled injections into those residuals; and a deuteron-like
high-dE/dx-depth PID proxy is fixed from total injected energy, stave depth, and
area-over-peak shape.  This gives a reproducible joint inference target for model
ranking without claiming calibrated particle truth.

For injected doublets,

`w(t) = A_1 T_s(t-t_1) + r A_1 T_s(t-t_1-Delta) + epsilon_{{r,s}}(t) + p`,

where `T_s` is the train-run stave template, `epsilon_{{r,s}}` is a raw residual
sampled from source run `r` and stave `s`, and `p` is the retained pedestal term.

Train-only template summaries:

{s26c.md_table(templates, ['stave', 'n_train_pulses', 'template_cfd20_sample', 'template_peak_sample', 'template_area'])}

## Methods

The strong traditional method is `deltaE_over_E_likelihood_template`: a bounded
two-pulse template/CFD fit for pile-up timing and energy, plus a diagonal
Gaussian likelihood-ratio PID model over DeltaE/E-like pulse-shape variables.
With standardized features `z_j`,

`log p(z | y) = -1/2 sum_j [(z_j - mu_yj)^2 / sigma_yj^2 + log sigma_yj^2] + log pi_y`.

The ML/NN comparison panel contains:

| family | implementation |
|---|---|
| Ridge | standardized ridge classifiers and ridge multi-output regressors |
| Gradient-boosted trees | histogram gradient-boosted classifiers/regressors |
| MLP | two-hidden-layer MLP classifiers/regressors with early stopping |
| 1D-CNN | compact convolutional waveform encoder plus PID head |
| New architecture | `joint_sequence_transformer`, a waveform transformer with pile-up, PID, and four-parameter recovery heads |
| Additional new architecture | `template_residual_boosted_stack_new`, a residual boosted stack using the traditional fit as a first stage |

For accepted injected doublets, timing and energy residuals are

`e_t = 10 ns (hat t - t_true)`,

`e_E = [(hat A_1 + hat A_2) - (A_1 + A_2)] / (A_1 + A_2)`,

and

`sigma68(e) = [Q_84(e)-Q_16(e)]/2`.

Confidence intervals are percentile 95% intervals from
`{int(cfg['ml']['bootstrap_samples'])}` held-out run-block bootstrap resamples.

## Overall held-out results

{s26c.md_table(ranked, ['method', 'winner_score', 'pid_auc', 'pid_balanced_accuracy', 'pid_efficiency', 'pid_purity', 'energy_fractional_sigma68', 'energy_fractional_sigma68_ci_low', 'energy_fractional_sigma68_ci_high', 'time_sigma68_ns', 'time_sigma68_ns_ci_low', 'time_sigma68_ns_ci_high', 'pileup_miss_rate', 'false_split_rate'])}

Relative to the traditional baseline, `{winner}` changes energy sigma68 by
`{_fmt(best['energy_fractional_sigma68'] - trad['energy_fractional_sigma68'])}`,
timing sigma68 by `{_fmt(best['time_sigma68_ns'] - trad['time_sigma68_ns'])}` ns,
and PID balanced accuracy by
`{_fmt(best['pid_balanced_accuracy'] - trad['pid_balanced_accuracy'])}`.

## Run-held-out stability

{s26c.md_table(by_run, ['method', 'heldout_run', 'pid_balanced_accuracy', 'pid_efficiency', 'pid_purity', 'energy_fractional_sigma68', 'time_sigma68_ns', 'pileup_miss_rate', 'false_split_rate'])}

## Strata, systematics, and caveats

The stratum scan covers injected pulse spacing, total energy proxy, stave/depth,
and PID class.  It is intended to expose whether a method wins only in an easy
spacing regime, one stave, or one ionization class.

{s26c.md_table(strata, ['stratum', 'value', 'method', 'pid_balanced_accuracy', 'energy_fractional_sigma68', 'time_sigma68_ns', 'pileup_miss_rate'])}

The main systematic is that PID truth is a deterministic raw-waveform proxy, not
an external particle label.  Pile-up and saturation conditions are controlled
injections into real ROOT-derived residuals, not independent hardware truth
flags.  The 18-sample window constrains sub-sample timing and makes pedestal
motion partly degenerate with late tails.  Bootstrap intervals resample held-out
runs, so they describe run-transfer uncertainty rather than event-level
asymptotic precision.  These limitations are acceptable for an architecture
bakeoff, but they are not sufficient for production PID calibration.

Runtime was `{runtime:.1f}` s on `{platform.platform()}`.
"""
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "REPORT.md").write_text(text, encoding="utf-8")


def main() -> None:
    started = time.time()
    s26c.TICKET = TICKET
    s26c.SLUG = SLUG
    s26c.OUT = OUT
    s26c.WORKER = WORKER
    s26c.RAW_ROOT_DIR = RAW_ROOT_DIR
    s26c.load_config = load_config
    s26c.write_report = write_report
    s26c.main()

    result_path = OUT / "result.json"
    result = json.loads(result_path.read_text(encoding="utf-8"))
    result["title"] = "PID timing-energy joint pulse representation benchmark"
    result["status"] = "complete"
    result["worker"] = WORKER
    result["claim_command"] = f"tn-ticket claim {WORKER} --project testbeam"
    result["novel_tickets_appended"] = []
    result["completion_audit"] = {
        "raw_root_reproduced": bool(result["raw_root_reproduction"]["passed"]),
        "required_methods_present": sorted(result["required_method_coverage"].values()),
        "winner_named": result["winner"]["name"],
        "run_bootstrap_cis_reported": True,
        "runtime_seconds_including_wrapper": time.time() - started,
    }
    result_path.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")

    manifest_path = OUT / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    manifest["command"] = f"{sys.executable} scripts/s29c_1783826036_4927_55a407fe_pid_timing_energy_joint_pulse_representation_benchmark.py"
    manifest["outputs_sha256"] = {
        p.name: sha256(p)
        for p in sorted(OUT.iterdir())
        if p.is_file() and p.name != "manifest.json"
    }
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
